import { type ArtisanConfig, normalizeArtisanConfig } from './types';

export const bankArtisanWorker: WorkerModule<ArtisanConfig, WorkerAccountView, WorkerWorldView, SessionCore> = {
    id: 'bank-artisan:unified',
    family: 'bank-artisan',
    kind: 'produce',
    trust: 'practice_passed',
    protectedAllowed: false,

    preflight(acct, cfg, world) {
        return artisanPreflight(acct, cfg, world);
    },

    estimate(acct, cfg, world) {
        return artisanEstimate(acct, cfg, world);
    },

    async run(session, cfg): Promise<RunOutcome> {
        const s = session as Session;
        const norm = normalizeArtisanConfig(cfg);
        const startTick = s.tick?.() ?? 0;
        const { isStopped } = watchWorkerStop(s, norm.stop);
        await Promise.resolve();
        if (isStopped()) {
            return toArtisanWorkerOutcome(
                { ok: false, summary: 'stop or session end requested', ticks: 0, produced: 0, failure: 'stopped' },
                s.name ?? 'unknown',
                norm,
                0,
                { stopped: true },
            );
        }
        try {
            const outcome = await runArtisan(s, norm, isStopped);
            const ticksElapsed = Math.max(0, (s.tick?.() ?? startTick) - startTick);
            return toArtisanWorkerOutcome(outcome, s.name ?? 'unknown', norm, ticksElapsed, { stopped: isStopped() });
        } catch (error) {
            await Promise.resolve();
            const msg = error instanceof Error ? error.message : String(error);
            const ticksElapsed = Math.max(0, (s.tick?.() ?? startTick) - startTick);
            return toArtisanWorkerOutcome(
                { ok: false, summary: msg, ticks: ticksElapsed, produced: 0, failure: msg },
                s.name ?? 'unknown',
                norm,
                ticksElapsed,
                { stopped: isStopped() },
            );
        }
    },
};

